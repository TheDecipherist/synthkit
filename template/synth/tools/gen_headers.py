#!/usr/bin/env python3
"""CSV -> generated headers for ExampleSynth.

The parameter table and the factory bank live in data/*.csv, with a provenance
column, and this writes the C++ the engine actually reads. Nothing else in the
build may hold a second copy of a range or a default.

    python3 tools/gen_headers.py              # writes src/generated/
    python3 tools/gen_headers.py --out DIR    # writes somewhere else (the ctest)

Why it is a generator and not hand-written code: playbook section 15. A research
pass widens a range in the CSV, nobody re-runs the generator, and the CSV and
the engine disagree in silence - green build, and most of the machine
unreachable. `ctest -R generated_headers_are_current` is the one line that
catches it, and it belongs in CI rather than in anybody's memory.

TODO(new machine): the SHAPE here is right for any machine; the CONTENT is not.
Replace data/params.csv and data/factory.csv with the real ones, decoded from
the firmware and the sysex spec, and extend the row type as the record needs.
"""
import argparse
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

BANNER = ("// GENERATED by tools/gen_headers.py from data/{src}. Do not edit.\n"
          "// Edit the CSV and re-run the generator; ctest -R "
          "generated_headers_are_current\n// fails the build when this file and "
          "the CSV disagree.\n")


def rows(path):
    with open(path, newline="") as f:
        # Comment lines carry the reasoning and the TODOs. The LAST one before
        # the data is the header, by convention, so the file reads top to bottom.
        lines = [l for l in f if l.strip()]
    header = None
    data = []
    for l in lines:
        if l.startswith("#"):
            header = l[1:].strip()
            continue
        data.append(l)
    if header is None:
        raise SystemExit(f"{path}: no '# id,name,...' header line")
    cols = [c.strip() for c in header.split(",")]
    return cols, list(csv.DictReader(data, fieldnames=cols))


def flt(v):
    """A C++ float literal. "0" must come out as 0.0f, never 0f, which does not
    compile - and a generator that emits code nobody reads is exactly where that
    hides until the build breaks."""
    return repr(float(v)) + "f"


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def gen_params(out):
    cols, rs = rows(os.path.join(ROOT, "data", "params.csv"))
    del cols
    b = [BANNER.format(src="params.csv"), "#pragma once\n#include <cstddef>\n\n",
         "namespace examplesynth {\n\n"]
    b.append("""/** One parameter. `provenance` is not decoration: it is the first thing to
    check when a patch sounds wrong, and a row is promoted the moment a source
    confirms it. See docs/provenance.md. */
struct ParamDef
{
    const char* id;
    const char* name;
    const char* kind;        // float | choice
    float       minimum, maximum, defaultValue;
    const char* unit;
    const char* provenance;
};

""")
    b.append(f"inline constexpr int kNumParams = {len(rs)};\n")
    b.append("inline constexpr ParamDef kParams[kNumParams] = {\n")
    for r in rs:
        b.append("    {{ {}, {}, {}, {}, {}, {}, {}, {} }},\n".format(
            cstr(r["id"]), cstr(r["name"]), cstr(r["kind"]),
            flt(r["min"]), flt(r["max"]), flt(r["default"]),
            cstr(r["unit"] or ""), cstr(r["provenance"] or "")))
    b.append("};\n\n")
    # Named indices so the engine never spells an id as a string literal twice.
    b.append("enum ParamIndex {\n")
    for i, r in enumerate(rs):
        b.append("    p{} = {},\n".format(
            "".join(w.capitalize() for w in r["id"].split("_")), i))
    b.append("};\n\n} // namespace examplesynth\n")
    write(os.path.join(out, "ExampleSynthParams.h"), "".join(b))
    return rs


def gen_factory(out, params):
    cols, rs = rows(os.path.join(ROOT, "data", "factory.csv"))
    ids = [p["id"] for p in params]
    stored = [c for c in cols if c in ids]
    missing = [c for c in ids if c not in cols]
    b = [BANNER.format(src="factory.csv"), "#pragma once\n",
         '#include "ExampleSynthParams.h"\n\n', "namespace examplesynth {\n\n"]
    b.append("""/** A factory program, exactly as the bank stores it.

    ROUND-TRIP EVERY BYTE. Only some of a real machine's record will be named on
    day one and the rest must travel verbatim, or sysex export is lossy and later
    attribution is impossible. `raw` is where the unnamed remainder goes on a
    real machine; here it stands empty and says so.

    The stored values are compared field by field against the engine's copy after
    load, in tools/tests_main.cpp and again in tools/spread_probe.cpp. That
    assertion is what found 272 of the H3500's 625 presets silently loading
    defaults, and 383 clamped values on the PCM 91, with every other test green. */
struct FactoryProgram
{
    const char* id;
    const char* name;
    const char* category;
""")
    b.append(f"    float value[{len(stored)}];   // in kStoredParam order\n")
    b.append("};\n\n")
    b.append(f"inline constexpr int kNumStored = {len(stored)};\n")
    b.append("/** Which parameter each column of FactoryProgram::value is, as an\n"
             "    index into kParams. The bank stores a SUBSET; anything not here\n"
             "    takes the parameter's own default. */\n")
    b.append("inline constexpr int kStoredParam[kNumStored] = {\n    ")
    b.append(", ".join(str(ids.index(c)) for c in stored))
    b.append("\n};\n\n")
    if missing:
        b.append("// Parameters the factory bank does not store, so they load their\n"
                 "// default: " + ", ".join(missing) + "\n\n")
    b.append(f"inline constexpr int kNumFactory = {len(rs)};\n")
    b.append("inline constexpr FactoryProgram kFactory[kNumFactory] = {\n")
    for r in rs:
        vals = ", ".join(flt(r[c]) for c in stored)
        b.append("    {{ {}, {}, {}, {{ {} }} }},\n".format(
            cstr(r["id"]), cstr(r["name"]), cstr(r["category"]), vals))
    b.append("};\n\n} // namespace examplesynth\n")
    write(os.path.join(out, "ExampleSynthFactory.h"), "".join(b))


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    old = None
    if os.path.exists(path):
        with open(path) as f:
            old = f.read()
    if old == text:
        print(f"unchanged {os.path.relpath(path, ROOT)}")
        return
    with open(path, "w") as f:
        f.write(text)
    print(f"wrote     {os.path.relpath(path, ROOT)}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "src", "generated"))
    a = ap.parse_args()
    params = gen_params(a.out)
    gen_factory(a.out, params)
    return 0


if __name__ == "__main__":
    sys.exit(main())
