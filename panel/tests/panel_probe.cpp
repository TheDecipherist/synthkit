// DO THE PANEL'S TAB AND PATH SEAMS DO WHAT THEY SAY, driven by real mouse
// events on a real NativePanel with a layout built here?
//
// The units test their own panels through their own probes; this is the
// package's own gate for the seams that exist only because a UNIT asked for
// them and that no template panel carries: the second drag handle on a tab
// (megasynth's LFO X and Y), the connection count in a tab's ring, the
// right-click that reports rather than selects, and a path window read as a
// FIGURE rather than a graph. Each is exercised by the handler the mouse
// reaches - mouseDown, mouseDrag, mouseUp on the component - and not by a
// second copy of the arithmetic.
//
//   1. THE Y GRIP IS ITS OWN SOURCE: a press on the Y grip of a two-handle cell,
//      dragged onto a knob, reports handle 1; a press on the name reports 0; a
//      one-handle cell reports 0 wherever it is pressed.
//   2. A RIGHT-CLICK ASKS AND DOES NOT ACT: onTabMenu fires with the cell, the
//      page does not change, and no drop follows.
//   3. THE COUNT IS DRAWN AND KEPT: setTabCount changes the pixels in that
//      cell's ring and survives a page change.
//   4. A FIGURE IS FREE WHERE A GRAPH IS NOT: the same drag of a middle point
//      past its neighbour is clamped on a graph and lands on a figure, and a
//      figure's ends are not pinned to the window's edges.
//   5. THE KEYS ARE PLAYED, NOT PRESSED: a click near a key's tip is louder
//      than one near its base, a drag across the bed plays every key it crosses
//      exactly once and never holds two, a release ends the note, and a black
//      key wins the overlap it is drawn on top of.
//
//   synthkit_panel_probe             run the checks
//   synthkit_panel_probe --selftest  break the handle hit test and the figure
//                                    mode and require checks 1 and 4 to notice
