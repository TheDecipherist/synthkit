void checkHandles (Probe& pr, bool expectFailure)
{
    auto& panel = pr.panel;
    std::printf ("1. the Y grip is its own source\n");
    for (int cell = 0; cell < 6; ++cell) panel.setTabHandles ("tabs", cell, cell == 2 || cell == 4 ? 2 : 1);
    if (panel.tabHandles ("tabs", 2) != 2 || panel.tabHandles ("tabs", 3) != 1)
        fail ("setTabHandles did not stick");

    const auto knob = pr.centre ("cutoff");
    const auto yGrip = panel.tabHandleBounds ("tabs", 2, 1).toFloat().getCentre();
    const auto xGrip = panel.tabHandleBounds ("tabs", 2, 0).toFloat().getCentre();
    const auto cellRect = panel.controlBounds ("tabs").toFloat();
    // The cell's name area: 12 px in from the cell's left edge, mid-height.
    const auto name2 = juce::Point<float> (cellRect.getX() + 241.0f - 20.0f + 12.0f, cellRect.getCentreY());
    std::printf ("   Y grip of LFO 3 at %s, X grip at %s, knob at %s\n",
                 yGrip.toString().toRawUTF8(), xGrip.toString().toRawUTF8(), knob.toString().toRawUTF8());

    pr.reset(); pr.drag (yGrip, knob);
    const bool yOk = pr.drops == 1 && pr.dropCell == 2 && pr.dropHandle == 1 && pr.dropTarget == "cutoff";
    std::printf ("   Y grip dragged onto the knob: %d drop(s), cell %d, handle %d, target %s\n",
                 pr.drops, pr.dropCell, pr.dropHandle, pr.dropTarget.toRawUTF8());
    if (yOk == expectFailure)
        fail (expectFailure ? "the Y grip was made to report handle 0 and this check did not notice"
                            : "a drag from the Y grip did not report handle 1 on cell 2 onto the knob");
    else ok (expectFailure ? "the broken Y grip was caught" : "the Y grip reports handle 1");

    pr.reset(); pr.drag (xGrip, knob);
    if (! (pr.drops == 1 && pr.dropCell == 2 && pr.dropHandle == 0)) fail ("a drag from the X grip did not report handle 0");
    else ok ("the X grip reports handle 0");

    pr.reset(); pr.drag (name2, knob);
    if (! (pr.drops == 1 && pr.dropCell == 2 && pr.dropHandle == 0)) fail ("a drag from the name did not report handle 0");
    else ok ("the cell's name still drags its first source");

    // A one-handle cell: pressed where a Y grip WOULD be, still handle 0.
    const auto cell3 = juce::Rectangle<float> (351.5f, 20.0f, 107.5f, 14.0f);
    pr.reset(); pr.drag ({ cell3.getRight() - 24.0f, cell3.getCentreY() }, knob);
    if (! (pr.drops == 1 && pr.dropCell == 3 && pr.dropHandle == 0)) fail ("a one-handle cell reported a Y handle");
    else ok ("a one-handle cell reports handle 0 wherever it is pressed");
}

void checkMenu (Probe& pr)
{
    auto& panel = pr.panel;
    std::printf ("2. a right-click asks and does not act\n");
    panel.setPage ("lfo", 0);
    const int before = panel.pageOf ("lfo");
    const auto cell4 = juce::Point<float> (462.0f + 30.0f, 27.0f);
    pr.reset();
    panel.mouseDown (pr.ev (cell4, cell4, juce::ModifierKeys (juce::ModifierKeys::rightButtonModifier)));
    panel.mouseDrag (pr.ev (pr.centre ("cutoff"), cell4, juce::ModifierKeys (juce::ModifierKeys::rightButtonModifier)));
    panel.mouseUp (pr.ev (pr.centre ("cutoff"), cell4, juce::ModifierKeys (juce::ModifierKeys::rightButtonModifier)));
    std::printf ("   right-click on cell 4: %d menu(s) for cell %d on %s, page %d -> %d, %d drop(s)\n",
                 pr.menus, pr.menuCell, pr.menuStrip.toRawUTF8(), before, panel.pageOf ("lfo"), pr.drops);
    if (pr.menus != 1 || pr.menuCell != 4 || pr.menuStrip != "tabs") fail ("onTabMenu did not fire once for cell 4");
    else ok ("onTabMenu fires with the strip and the cell");
    if (panel.pageOf ("lfo") != before) fail ("a right-click selected the tab");
    else ok ("the tab was not selected");
    if (pr.drops != 0) fail ("a right-click started a drag and dropped");
    else ok ("no drag followed the right-click");
    // And a plain click still selects, so the two are told apart.
    pr.reset();
    panel.mouseDown (pr.ev (cell4, cell4)); panel.mouseUp (pr.ev (cell4, cell4));
    if (panel.pageOf ("lfo") != 4) fail ("a plain click on cell 4 did not select it");
    else ok ("a plain click still selects the tab");
    panel.setPage ("lfo", 0);
}

void checkCounts (Probe& pr)
{
    auto& panel = pr.panel;
    std::printf ("3. the count is drawn and kept\n");
    const auto strip = panel.controlBounds ("tabs");
    // The pixels of cell 1's right third, where the ring glyph is.
    const juce::Rectangle<int> region (130 + 70, 20, 37, 14);
    panel.setTabCount ("tabs", 1, 0);
    const auto plain = panel.createComponentSnapshot (strip);
    panel.setTabCount ("tabs", 1, 7);
    const auto counted = panel.createComponentSnapshot (strip);
    int differing = 0;
    for (int y = region.getY(); y < region.getBottom(); ++y)
        for (int x = region.getX(); x < region.getRight(); ++x)
            if (plain.getPixelAt (x - strip.getX(), y - strip.getY()) != counted.getPixelAt (x - strip.getX(), y - strip.getY()))
                ++differing;
    std::printf ("   count 0 -> 7 on cell 1: %d pixels changed in the ring's region\n", differing);
    if (differing < 8) fail ("setTabCount changed nothing visible in cell 1's ring");
    else ok ("the count is drawn in the ring");
    panel.setPage ("lfo", 3);
    if (panel.tabCount ("tabs", 1) != 7) fail ("the count did not survive a page change");
    else ok ("the count survives a page change");
    panel.setPage ("lfo", 0);
}

void checkKeys (Probe& pr)
{
    auto& panel = pr.panel;
    std::printf ("5. the keys are played, not pressed\n");

    // ---- velocity is WHERE DOWN THE KEY the click landed -------------------
    // A fixed velocity gives an on-screen keyboard exactly one dynamic, and
    // every patch that answers to velocity then has one sound from the panel.
    const auto c3 = panel.controlBounds ("kbd_1").toFloat();
    const auto atY = [&] (float f) { return juce::Point<float> (c3.getCentreX(),
                                                                c3.getY() + c3.getHeight() * f); };
    pr.reset();
    panel.mouseDown (pr.ev (atY (0.90f), atY (0.90f)));
    const float tip = pr.notes.empty() ? -1.0f : pr.notes.front().vel;
    panel.mouseUp (pr.ev (atY (0.90f), atY (0.90f)));
    pr.reset();
    panel.mouseDown (pr.ev (atY (0.10f), atY (0.10f)));
    const float base = pr.notes.empty() ? -1.0f : pr.notes.front().vel;
    panel.mouseUp (pr.ev (atY (0.10f), atY (0.10f)));
    std::printf ("   C3 struck at the tip %.3f, at the base %.3f\n", tip, base);
    if (! (tip > base + 0.3f)) fail ("a click at the tip is not louder than one at the base");
    else ok ("velocity comes from how far down the key the click landed");
    if (! (base > 0.0f && tip <= 1.0f))
        fail ("velocity leaves its range - a note on at 0 is a note OFF in MIDI");
    else ok ("the quietest key still speaks and the loudest does not overflow");

    // ---- one click is one note, and the release ends it --------------------
    pr.reset();
    panel.mouseDown (pr.ev (atY (0.6f), atY (0.6f)));
    const bool litWhilePlaying = panel.controlLit ("kbd_1");
    panel.mouseUp (pr.ev (atY (0.6f), atY (0.6f)));
    std::printf ("   one click on C3: %d event(s), lit while sounding %d, lit after %d\n",
                 (int) pr.notes.size(), (int) litWhilePlaying, (int) panel.controlLit ("kbd_1"));
    if (! (pr.notes.size() == 2 && pr.notes[0].on && pr.notes[0].midi == 60
           && ! pr.notes[1].on && pr.notes[1].midi == 60))
        fail ("a click on C3 did not report exactly one note on and one note off for 60");
    else ok ("a click is one note on and the release is its note off");
    if (! litWhilePlaying) fail ("the key did not light while it was sounding");
    else if (panel.controlLit ("kbd_1")) fail ("the key stayed lit after the note ended");
    else ok ("the key lights while it sounds and goes out with it");

    // ---- a black key wins the overlap it is drawn on top of ---------------
    // C# is drawn over the right-hand side of C and the left-hand side of D. The
    // hit order runs backwards through the layout, which lists the blacks last,
    // so the black is tested first - forwards, every click on a black key would
    // answer "white".
    const auto cs3 = panel.controlBounds ("kbd_2").toFloat();
    pr.reset();
    panel.mouseDown (pr.ev (cs3.getCentre(), cs3.getCentre()));
    panel.mouseUp (pr.ev (cs3.getCentre(), cs3.getCentre()));
    std::printf ("   a click in the middle of C#3 played %d\n",
                 pr.notes.empty() ? -1 : pr.notes.front().midi);
    if (! (pr.notes.size() == 2 && pr.notes.front().midi == 61))
        fail ("a click on the black key landed on the white underneath it");
    else ok ("a black key wins the overlap");

    // ---- the glissando -----------------------------------------------------
    // Along the BOTTOM of the bed, below where the black keys reach, so the path
    // crosses the seven whites of the octave and nothing else. Every key it
    // crosses plays exactly once, in order, and never two at a time.
    pr.reset();
    std::vector<juce::Point<float>> path;
    for (float x = 22.0f; x <= 186.0f; x += 4.0f) path.push_back ({ x, 352.0f });
    pr.sweep (path);
    std::vector<int> played;
    int holding = 0, everTwo = 0;
    for (const auto& n : pr.notes)
    {
        if (n.on) { played.push_back (n.midi); if (++holding > 1) ++everTwo; }
        else --holding;
    }
    juce::String heard;
    for (int m : played) heard += juce::String (m) + " ";
    std::printf ("   dragged across the whites: %s(%d on, %d left holding)\n",
                 heard.toRawUTF8(), (int) played.size(), holding);
    const std::vector<int> want { 60, 62, 64, 65, 67, 69, 71 };
    if (played != want) fail ("a drag did not play every white key it crossed exactly once, in order");
    else ok ("a drag plays every key it crosses once, in pitch order");
    if (everTwo != 0) fail ("the drag held two notes at once - a finger on a keybed holds one");
    else ok ("crossing into a key releases the one before it");
    if (holding != 0) fail ("the drag ended with a note still sounding");
    else ok ("the release ends the glissando");

    // ---- a note from outside lights its key --------------------------------
    // Every note that does not come from this panel - a wire, the host, an
    // arpeggiator - and the panel has no idea those exist, so the unit says so.
    panel.setKeyLit (67, true);
    const bool litFromOutside = panel.controlLit ("kbd_8");
    panel.setKeyLit (67, false);
    panel.setKeyLit (999, true);                     // a note off the keyboard is ignored, not asserted
    std::printf ("   setKeyLit(67): G3 lit %d, and after clearing %d\n",
                 (int) litFromOutside, (int) panel.controlLit ("kbd_8"));
    if (! litFromOutside || panel.controlLit ("kbd_8"))
        fail ("setKeyLit did not light the key a MIDI note names");
    else ok ("a note played from outside lights its own key");
}

void checkFigure (Probe& pr, bool expectFailure)
{
    auto& panel = pr.panel;
    std::printf ("4. a figure is free where a graph is not\n");
    const auto plot = juce::Rectangle<float> (105.0f, 65.0f, 550.0f, 170.0f);
    const auto at = [&] (float x, float y) { return juce::Point<float> (plot.getX() + plot.getWidth() * x,
                                                                       plot.getY() + plot.getHeight() * (1.0f - y)); };
    const std::vector<synthkit::NativePanel::PathPoint> start = { { 0.3f, 0.2f, 0.0f }, { 0.5f, 0.8f, 0.0f }, { 0.7f, 0.2f, 0.0f } };

    // ON A GRAPH: the middle point cannot pass its neighbour and the ends pin.
    pr.path = start; pr.reset();
    panel.setPathMode ("path", synthkit::NativePanel::kPathTime);
    pr.drag (at (0.5f, 0.8f), at (0.9f, 0.8f));
    const bool graphClamped = pr.edits > 0 && pr.edited.size() == 3 && pr.edited[1].x <= 0.7f + 1.0e-3f
                           && pr.edited[0].x == 0.0f && pr.edited[2].x == 1.0f;
    std::printf ("   graph: middle point dragged to x 0.9 landed at %.3f, ends at %.2f and %.2f (%d edits)\n",
                 pr.edits ? pr.edited[1].x : -1.0f, pr.edits ? pr.edited[0].x : -1.0f, pr.edits ? pr.edited[2].x : -1.0f, pr.edits);
    if (! graphClamped) fail ("a graph let a point pass its neighbour or left its ends unpinned");
    else ok ("a graph clamps the point and pins its ends");

    // ON A FIGURE: the same drag lands, and the ends stay where they were drawn.
    pr.path = start; pr.reset();
    panel.setPathMode ("path", expectFailure ? synthkit::NativePanel::kPathTime : synthkit::NativePanel::kPathFigure);
    pr.drag (at (0.5f, 0.8f), at (0.9f, 0.8f));
    const bool figureFree = pr.edits > 0 && pr.edited.size() == 3 && pr.edited[1].x > 0.85f
                         && std::abs (pr.edited[0].x - 0.3f) < 1.0e-3f && std::abs (pr.edited[2].x - 0.7f) < 1.0e-3f;
    std::printf ("   figure: the same drag landed at %.3f, ends at %.2f and %.2f (%d edits)\n",
                 pr.edits ? pr.edited[1].x : -1.0f, pr.edits ? pr.edited[0].x : -1.0f, pr.edits ? pr.edited[2].x : -1.0f, pr.edits);
    if (figureFree == expectFailure)
        fail (expectFailure ? "the figure was made a graph and this check did not notice"
                            : "a figure clamped its point or pinned its ends");
    else ok (expectFailure ? "the broken figure mode was caught" : "a figure's points are free on both axes and its ends are its own");
    if (panel.pathMode ("path") != (expectFailure ? synthkit::NativePanel::kPathTime : synthkit::NativePanel::kPathFigure))
        fail ("pathMode does not read back what was set");

    // A TRACE WINDOW IGNORES THE HAND.
    pr.path = start; pr.reset();
    panel.setPathMode ("path", synthkit::NativePanel::kPathTrace);
    pr.drag (at (0.5f, 0.8f), at (0.9f, 0.8f));
    if (pr.edits != 0) fail ("a trace window took an edit");
    else ok ("a trace window is not editable");
    panel.setPathMode ("path", synthkit::NativePanel::kPathTime);
}

/** THE STEP GRID (2026-09-14): MegaSynth's ARP and CLIP pages draw their
    patterns with this, in the machine's own plate rather than the shared shell's
    tabs. The seam is the path editor's - the host owns the pattern and the panel
    owns the gesture - so what is checked here is that a hand reaches the cell it
    aimed at, that a click both fills and erases, that a drag gives a note a
    LENGTH, and that a one-row lane is painted rather than toggled. */
void checkGrid (Probe& pr, bool expectFailure)
{
    auto& panel = pr.panel;
    std::printf ("6. a step grid is filled, erased, lengthened and painted\n");
    // The cell centres, from the layout's own plot rects, so the test aims where
    // the painter draws rather than at figures invented for it.
    const auto rollAt = [] (int col, int row)
    {
        const float cw = 316.0f / 16.0f, ch = 124.0f / 8.0f;
        return juce::Point<float> (22.0f + cw * ((float) col + 0.5f),
                                   402.0f + ch * ((float) (8 - 1 - row) + 0.5f));
    };
    const auto velAt = [] (int col, float level)
    {
        const float cw = 316.0f / 16.0f;
        return juce::Point<float> (362.0f + cw * ((float) col + 0.5f), 402.0f + 60.0f * (1.0f - level));
    };

    pr.roll.clear(); pr.reset(); pr.gridEdits = 0;
    panel.mouseDown (pr.ev (rollAt (2, 3), rollAt (2, 3)));
    panel.mouseUp   (pr.ev (rollAt (2, 3), rollAt (2, 3)));
    const bool filled = pr.roll.size() == 1 && pr.roll[0].col == 2 && pr.roll[0].row == 3
                     && pr.roll[0].len == 1 && pr.roll[0].value > 0.0f;
    std::printf ("   a click on an empty cell left %d cell(s)%s\n", (int) pr.roll.size(),
                 pr.roll.empty() ? "" : juce::String::formatted (" at col %d row %d",
                     pr.roll[0].col, pr.roll[0].row).toRawUTF8());
    if (filled == expectFailure)
        fail (expectFailure ? "a dead host was not noticed: the grid filled anyway"
                            : "a click on an empty cell did not fill it");
    else ok (expectFailure ? "the dead host was caught" : "a click fills the cell it lands on");

    if (! expectFailure)
    {
        panel.mouseDown (pr.ev (rollAt (2, 3), rollAt (2, 3)));
        panel.mouseUp   (pr.ev (rollAt (2, 3), rollAt (2, 3)));
        if (! pr.roll.empty()) fail ("a click on a filled cell did not erase it");
        else ok ("and a click on a filled cell erases it");

        // A LENGTH, which is what separates a note from a tick. The drag starts
        // on the cell it just laid down and runs right along the same row.
        pr.roll.clear();
        pr.drag (rollAt (2, 3), rollAt (5, 3));
        const bool lengthened = pr.roll.size() == 1 && pr.roll[0].col == 2 && pr.roll[0].len == 4;
        std::printf ("   a drag from column 2 to column 5 left %d cell(s), length %d\n",
                     (int) pr.roll.size(), pr.roll.empty() ? -1 : pr.roll[0].len);
        if (! lengthened) fail ("a drag along the row did not lengthen the note");
        else ok ("a drag along the row gives the note its length");

        // AND A LANE IS PAINTED. One row, so the pointer's HEIGHT is the value
        // and every column the hand crosses takes it.
        pr.vel.clear();
        pr.sweep ({ velAt (0, 0.75f), velAt (1, 0.75f), velAt (2, 0.75f), velAt (3, 0.75f) });
        bool painted = pr.vel.size() == 4;
        for (const auto& q : pr.vel) painted = painted && std::abs (q.value - 0.75f) < 0.05f;
        std::printf ("   a sweep across four columns of the lane left %d cell(s) at %.2f\n",
                     (int) pr.vel.size(), pr.vel.empty() ? -1.0f : pr.vel[0].value);
        if (! painted) fail ("a one-row lane did not take the pointer's height into every column");
        else ok ("a lane is painted, not toggled");

        // THE DIVISIONS ARE A SETTING, so they read back.
        panel.setGridSize ("roll", 0, 8);
        if (panel.gridSize ("roll") != juce::Point<int> (8, 8))
            fail ("setGridSize did not read back, or a zero did not leave its axis alone");
        else ok ("the divisions read back and a zero leaves its axis alone");
        panel.setGridSize ("roll", 0, 16);

        panel.setGridPlayhead ("roll", 3);
        if (panel.gridPlayhead ("roll") != 3) fail ("the playhead did not read back");
        else ok ("the playhead reads back");
        panel.setGridPlayhead ("roll", -1);
    }
}

